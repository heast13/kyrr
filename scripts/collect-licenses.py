def generated_license(root, pkg):
    """License text for a crate without license file, from its Cargo.toml."""
    expr = pkg.get("license") or ""
    choices = [c.strip() for c in expr.split(" OR ")]
    authors = ", ".join(a.split(" <")[0] for a in pkg.get("authors") or []) or f"the {pkg['name']} authors"
    header = (f"{pkg['name']} {pkg['version']} publishes no license file. Its Cargo.toml names the\n"
              f"license \"{expr}\"; the text below is that license with the crate's authors.\n"
              f"Source: {pkg.get('repository') or 'https://crates.io/crates/' + pkg['name']}\n\n")
    if "MIT" in choices:
        return "LICENSE-MIT.txt", header + MIT.format(authors=authors)
    if "Apache-2.0" in choices:
        with open(os.path.join(root, "LICENSE-APACHE"), encoding="utf-8") as f:
            return "LICENSE-APACHE.txt", header + f.read()
    if "BSL-1.0" in choices:
        return "LICENSE-BSL.txt", header + BSL.format(authors=authors)
    return None


def license_files(pkg_dir):
    found = []
    for base, dirs, files in os.walk(pkg_dir):
        dirs[:] = [d for d in dirs if d not in ("target", ".git", "tests", "examples", "benches")]
        for f in files:
            if f.lower().startswith(PATTERNS):
                found.append(os.path.join(base, f))
    return sorted(found)


def main():
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    out_dir = sys.argv[1]
    meta = json.loads(subprocess.run(
        ["cargo", "metadata", "--format-version", "1", "--filter-platform", TARGET],
        cwd=root, check=True, capture_output=True, text=True, encoding="utf-8").stdout)
    packages = {(p["name"], p["version"]): p for p in meta["packages"]}
    workspace = set(meta["workspace_members"])

    rows, missing = [], []
    for name, version in sorted(linked_crates(root)):
        pkg = packages.get((name, version))
        if pkg is None:
            continue  # not built for the target (cargo tree is less strict than metadata)
        if pkg["id"] in workspace:
            continue  # kyrr itself: LICENSE-MIT / LICENSE-APACHE at the top level
        pkg_dir = os.path.dirname(pkg["manifest_path"])
        files = license_files(pkg_dir)
        dest = os.path.join(out_dir, f"{name}-{version}")
        if not files:
            generated = generated_license(root, pkg)
            if generated is None:
                missing.append(f"{name} {version}")
                continue
            os.makedirs(dest, exist_ok=True)
            with open(os.path.join(dest, generated[0]), "w", encoding="utf-8", newline="\n") as f:
                f.write(generated[1])
            rows.append((name, version, pkg.get("license") or "see files", 1))
            continue
        os.makedirs(dest, exist_ok=True)
        for f in files:
            rel = os.path.relpath(f, pkg_dir).replace(os.sep, "-")
            shutil.copyfile(f, os.path.join(dest, rel))
        rows.append((name, version, pkg.get("license") or "see files", len(files)))

    if missing:
        sys.exit("no license file found for: " + ", ".join(missing))
    with open(os.path.join(out_dir, "CRATES.md"), "w", encoding="utf-8", newline="\n") as f:
        f.write("# Rust crates linked into kyrr.exe and kyrr_apo.dll\n\n")
        f.write("Each crate's license files are in the folder `<crate>-<version>/`.\n\n")
        f.write("| Crate | Version | License |\n|---|---|---|\n")
        for name, version, lic, _ in rows:
            f.write(f"| {name} | {version} | {lic} |\n")
    print(f"{len(rows)} crates, license files in {out_dir}")


if __name__ == "__main__":
    main()
